function subscribe(callback: () => void) {
  window.addEventListener('storage', callback);
  window.addEventListener(storageKey, callback);
  return () => {
    window.removeEventListener('storage', callback);
    window.removeEventListener(storageKey, callback);
  };
}

export function usePreviewLanguage() {
  const english = useContext(Language);
  // Stable across renders so components keying off `t` (e.g. table columns) don't rebuild every keystroke.
  const t = useCallback((dutch: string) => english ? dictionary[dutch] ?? dutch : dutch, [english]);
  return { english, t };
}

export function PreviewText({ children }: { children: string }) {
  return usePreviewLanguage().t(children);
}

export function PreviewProductName({ sku, children, limit }: { sku: string; children: string; limit?: number }) {
  const { english } = usePreviewLanguage();
  const names = useContext(ProductNames);
  const name = english ? (names[sku.toUpperCase()] ?? children)
    .replace(/\b(\d+)\s*knop(?:pen|s)?\b/gi, '$1-button')
    .replace(/\bklap(?:sleutel|sluetel)\b/gi, 'flip key')
    .replace(/\bexterne afstandsbediening\b/gi, 'external remote')
    .replace(/\bafstandsbediening\b/gi, 'remote')
    .replace(/\boplaadbare batterij\b/gi, 'rechargeable battery')
    .replace(/\bnoodsleutelbaard\b/gi, 'emergency key blade')
    .replace(/\bsleutelbaard\b/gi, 'key blade')
    .replace(/\bbehuizing\b/gi, 'housing')
    .replace(/\bsoftware voor automerken sleutels\b/gi, 'vehicle key software')
    .replace(/\bkabel voor connectie met\b/gi, 'connection cable for')
    .replace(/\b(?:nieuw|nieuwe)\b/gi, 'new') : children;
  return limit ? name.slice(0, limit) : name;
}

