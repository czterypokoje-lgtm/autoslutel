export function usePreviewLanguage() {
  const english = useContext(Language);
  return { english, t: (dutch: string) => english ? dictionary[dutch] ?? dutch : dutch };
}

export function PreviewText({ children }: { children: string }) {
  return usePreviewLanguage().t(children);
}

export function PreviewDate({ value }: { value: number }) {
  const { english } = usePreviewLanguage();
  return new Intl.DateTimeFormat(english ? 'en-GB' : 'nl-NL', {
    weekday: 'long', day: 'numeric', month: 'long', timeZone: 'Europe/Amsterdam',
  }).format(value);
}

export function PreviewInput({ placeholder, 'aria-label': label, ...props }: ComponentProps<'input'>) {
  const { t } = usePreviewLanguage();
  return <input {...props} placeholder={placeholder && t(placeholder)} aria-label={label && t(label)} />;
}

export default function PreviewLanguage({ children }: { children: ReactNode }) {
  const english = useSyncExternalStore(subscribe, () => localStorage.getItem(storageKey) === 'en', () => false);
  useEffect(() => {
    const root = document.documentElement;
    const previous = root.lang;
    root.lang = english ? 'en' : 'nl';
    return () => { root.lang = previous; };
  }, [english]);
  return <Language.Provider value={english}>
    {children}
    <div role="group" aria-label={english ? 'Interface language' : 'Interfacetaal'} className={`${styles.readonlyBanner} ${styles.languageBanner}`}>
      {['NL', 'EN'].map((lang) => <button key={lang} type="button" aria-pressed={english === (lang === 'EN')} onClick={() => {
        localStorage.setItem(storageKey, lang.toLowerCase());
        window.dispatchEvent(new Event(storageKey));
      }}>{lang}</button>)}
    </div>
  </Language.Provider>;
}
